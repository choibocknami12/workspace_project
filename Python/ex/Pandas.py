import pandas as pd

data = {
    '나이': [50, 28, 33, None, 55],
    '소득': [3000, 4000, None, 5000, None],
    '도시': ['서울', '경기', '부산', '대구', '인천']
    }

df = pd.DataFrame(data)
print(df.isna().sum())
# 나이    1
# 소득    2
# 도시    0
# dtype: int64
print(df.isna().any())
# 나이     True
# 소득     True
# 도시    False
# dtype: bool

df['도시'] = df['도시'].replace('서울', 'Seoul')
print(df)
#      나이      소득     도시
# 0  50.0  3000.0  Seoul
# 1  28.0  4000.0     경기
# 2  33.0     NaN     부산
# 3   NaN  5000.0     대구
# 4  55.0     NaN     인천

df['age_str'] = df['나이'].map(lambda x: f'나이: {x}살' if pd.notna(x) else '나이: 정보없음')
print(df)
#      나이      소득     도시    age_str
# 0  50.0  3000.0  Seoul  나이: 50.0살
# 1  28.0  4000.0     경기  나이: 28.0살
# 2  33.0     NaN     부산  나이: 33.0살
# 3   NaN  5000.0     대구   나이: 정보없음
# 4  55.0     NaN     인천  나이: 55.0살

# 소득이 4000 미만인 경우 소득을 3500으로 설정
df.loc[df['소득'] < 4000, '소득'] = 3500
print(df)
#      나이      소득     도시    age_str
# 0  50.0  3500.0  Seoul  나이: 50.0살
# 1  28.0  4000.0     경기  나이: 28.0살
# 2  33.0     NaN     부산  나이: 33.0살
# 3   NaN  5000.0     대구   나이: 정보없음
# 4  55.0     NaN     인천  나이: 55.0살

# 나이가 30 이상인 경우 나이를 유지하고, 그렇지 않은 경우 0으로 설정
df['age_where'] = df['나이'].where(df['나이'] >= 30, other = 0)
print(df)
#      나이      소득     도시    age_str  age_where
# 0  50.0  3500.0  Seoul  나이: 50.0살       50.0
# 1  28.0  4000.0     경기  나이: 28.0살        0.0
# 2  33.0     NaN     부산  나이: 33.0살       33.0
# 3   NaN  5000.0     대구   나이: 정보없음        0.0
# 4  55.0     NaN     인천  나이: 55.0살       55.0

